post() {
  curl -s -X POST "$BASE/$1" \
    -H "Content-Type: application/json" \
    -d "$2"
}

create_dish() {
  local cat_id="$1"
  local name="$2"
  local desc="$3"
  local price="$4"
  local weight="$5"

  # 1. Product (container)
  local product
  product=$(post "products" "{\"categoryId\":\"$cat_id\",\"name\":\"$name\",\"description\":\"$desc\",\"active\":true}")
  local product_id
  product_id=$(echo "$product" | python3 -c "import sys,json; print(json.load(sys.stdin)['id'])")

  # 2. MenuItem
  local item
  item=$(post "menu-items" "{\"productId\":\"$product_id\",\"name\":\"$name\",\"active\":true}")
  local item_id
  item_id=$(echo "$item" | python3 -c "import sys,json; print(json.load(sys.stdin)['id'])")

  # 3. Image
  post "menu-item-images" "{\"menuItemId\":\"$item_id\",\"url\":\"$IMG\"}" > /dev/null

  # 4. Size + price
  post "menu-item-sizes" "{\"menuItemId\":\"$item_id\",\"label\":\"WEIGHT\",\"sizeValue\":$weight,\"sizeUnit\":\"GRAM\",\"price\":$price}" > /dev/null

  echo "  ✓ $name"
}

create_category() {
  local name="$1"
  local cat
  cat=$(post "categories" "{\"name\":\"$name\"}")
  echo "$cat" | python3 -c "import sys,json; print(json.load(sys.stdin)['id'])"
}

